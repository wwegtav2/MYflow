const LANG_KEY = 'myflow_language';

function getStoredLang() {
  try {
    return localStorage.getItem(LANG_KEY) || 'th';
  } catch {
    return 'th';
  }
}

const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(getStoredLang);

  const toggleLang = () => {
    setLang(prev => {
      const next = prev === 'th' ? 'en' : 'th';
      localStorage.setItem(LANG_KEY, next);
      return next;
    });
  };

  const t = (key) => {
    return translations[lang]?.[key] ?? translations['th']?.[key] ?? key;
  };

  const locale = lang === 'th' ? 'th-TH' : 'en-US';

  return (
    <LanguageContext.Provider value={{ lang, toggleLang, t, locale }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}
